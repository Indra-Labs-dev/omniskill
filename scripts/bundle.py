#!/usr/bin/env python3
"""Build single-file instruction bundles for platforms that cannot load a skill folder.

Each bundle = core (SKILL.md without frontmatter) + one mode file, optionally with
the evidence protocol inlined. Paste it into a system prompt, custom instructions,
a Modelfile SYSTEM block or a project instruction file (see adapters/).

Usage
  python3 scripts/bundle.py --mode pro --out dist/
  python3 scripts/bundle.py --mode all --with-evidence --out dist/
  python3 scripts/bundle.py --mode quick --stdout

Writes only files named omniskill-<mode>.md inside --out. Refuses to overwrite a
file that it did not generate (no bundle marker) unless --force is given.
Exit codes: 0 ok, 1 refused or source missing, 2 usage error.
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from _common import FrontmatterError, estimate_tokens, parse_frontmatter  # noqa: E402

ROOT = Path(__file__).resolve().parent.parent
MODES = ("quick", "pro", "autonomous", "audit")
MARKER = "<!-- omniskill-bundle: generated by scripts/bundle.py; edit the sources, not this file -->"


def build(mode: str, with_evidence: bool = False, root: Path = ROOT) -> str:
    meta, core = parse_frontmatter((root / "SKILL.md").read_text(encoding="utf-8"))
    version = (meta.get("metadata") or {}).get("version", "unknown")
    parts = [
        MARKER,
        f"<!-- omniskill {version} | mode: {mode.upper()} -->",
        "",
        "> Single-file bundle. Files referenced below (modes/, references/, scripts/) may not be",
        "> available in this environment: rely on the text here, and use a script only if you can",
        "> see it exists.",
        "",
        core.strip(),
    ]
    if mode != "quick":
        parts += ["", "---", "", (root / "modes" / f"{mode}.md").read_text(encoding="utf-8").strip()]
    if with_evidence:
        parts += ["", "---", "", (root / "references" / "evidence-protocol.md").read_text(encoding="utf-8").strip()]
    return "\n".join(parts) + "\n"


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("--mode", required=True, choices=[*MODES, "all"])
    parser.add_argument("--with-evidence", action="store_true", help="inline references/evidence-protocol.md")
    target = parser.add_mutually_exclusive_group(required=True)
    target.add_argument("--out", type=Path, help="output directory")
    target.add_argument("--stdout", action="store_true", help="print instead of writing")
    parser.add_argument("--force", action="store_true", help="overwrite files without the bundle marker")
    args = parser.parse_args(argv)

    modes = MODES if args.mode == "all" else (args.mode,)
    if args.stdout and len(modes) > 1:
        print("error: --stdout works with a single mode", file=sys.stderr)
        return 2
    try:
        bundles = {m: build(m, args.with_evidence) for m in modes}
    except (OSError, FrontmatterError) as exc:
        print(f"error: cannot read sources: {exc}", file=sys.stderr)
        return 1

    if args.stdout:
        sys.stdout.write(bundles[modes[0]])
        return 0

    args.out.mkdir(parents=True, exist_ok=True)
    status = 0
    for mode, text in bundles.items():
        dest = args.out / f"omniskill-{mode}.md"
        if dest.exists() and not args.force:
            head = dest.read_text(encoding="utf-8", errors="replace").splitlines()[:1]
            if head != [MARKER]:
                print(f"refused: {dest} exists and was not generated by bundle.py (use --force)", file=sys.stderr)
                status = 1
                continue
        dest.write_text(text, encoding="utf-8")
        print(f"wrote {dest} (~{estimate_tokens(text)} tokens)")
    return status


if __name__ == "__main__":
    sys.exit(main())
